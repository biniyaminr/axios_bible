/// True when the name resolves to a New Testament book, false when it
/// resolves to an Old Testament or deuterocanonical one, null when the
/// name is not recognized.
bool? isNewTestamentBook(String name) {
  final id = resolveBookId(name);
  if (id == null) return null;
  return newTestamentIds.contains(id);
}

String _normalize(String name) {
  var s = name.trim().toLowerCase();
  // Strip Ethiopic full stop and Latin punctuation.
  s = s.replaceAll(RegExp(r'[።\.\,\:\;]'), '');
  s = s.replaceAll(RegExp(r'\s+'), ' ').trim();
  // Leading roman numerals / ordinals -> digits: "i samuel" -> "1 samuel".
  s = s.replaceFirstMapped(
    RegExp(r'^(iii|ii|i|1st|2nd|3rd|first|second|third)\s'),
    (m) => switch (m[1]) {
      'i' || '1st' || 'first' => '1 ',
      'ii' || '2nd' || 'second' => '2 ',
      _ => '3 ',
    },
  );
  if (s.startsWith('the ')) s = s.substring(4);
  return s;
}

