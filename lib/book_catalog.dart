/// Canonical Bible book identification.
///
/// Translations key their data by localized book names ("Genesis",
/// "ኦሪት ዘፍጥረት", "I Samuel", "1 Samuel"…). To keep the reader on the same
/// book when switching translations — including NT-only or Apocrypha-bearing
/// ones where positional indexes disagree — book names are resolved to
/// OSIS-style canonical IDs and matched by ID.
library;

/// Resolves a translation's book name/key to a canonical ID (e.g. 'GEN',
/// '1SA', 'MAT'). Returns null when the name is not recognized (e.g. a
/// translation in a language without aliases yet); callers should fall back
/// to positional mapping.
String? resolveBookId(String name) => _aliases[_normalize(name)];

